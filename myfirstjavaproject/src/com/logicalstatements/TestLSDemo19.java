package com.logicalstatements;

//WAP to swap elements using third variable.
//WAP to swap elements without using third variable.
//WAP to swap elements using  bitwise XOR operators.
public class TestLSDemo19 {

	public static void main(String[] args) {
		int x = 10;
		int y = 20;

		int temp = x;
		x = y;
		y = temp;

		System.out.println("X value : " + x);
		System.out.println("Y value : " + y);

	}

}
